# 4. First-run: build the unsigned .shortcut file
# --------------------------------------------------------------------------- #
#
# A ``.shortcut`` file is an Apple *property list* describing a Shortcuts
# workflow. The heavy lifting is the ``WFWorkflowActions`` array: an ordered
# list of ``{WFWorkflowActionIdentifier, WFWorkflowActionParameters}`` dicts.
# Actions pass values to each other via magic variables — a producing action
# is tagged with a ``UUID`` parameter, and consumers reference its output with
# an ``ActionOutput`` attachment carrying that ``OutputUUID`` and the action's
# ``OutputName``. We use the documented, stable action identifiers:
#
#   is.workflow.actions.detect.dictionary  -- "Get Dictionary from Input"
#   is.workflow.actions.getvalueforkey     -- "Get Dictionary Value"
#   is.workflow.actions.addnewreminder     -- "Add New Reminder"


def _action(identifier: str, params: dict[str, Any]) -> dict[str, Any]:
    return {
        "WFWorkflowActionIdentifier": identifier,
        "WFWorkflowActionParameters": params,
    }


def _output_attachment(uuid: str, output_name: str) -> dict[str, Any]:
    """A magic-variable reference to a prior action's output."""
    return {
        "OutputUUID": uuid,
        "OutputName": output_name,
        "Type": "ActionOutput",
    }


def _var_token(uuid: str, output_name: str) -> dict[str, Any]:
    """Wrap an output attachment as a standalone tokenized value."""
    return {
        "WFSerializationType": "WFTextTokenAttachment",
        "Value": _output_attachment(uuid, output_name),
    }


def _text_token(pieces: Sequence[tuple[str, str]], *, joiner: str = "") -> dict[str, Any]:
    """Build an interpolated text token from (uuid, output_name) variables.

    Each variable becomes a single object-replacement char (``\\ufffc``) in the
    backing string, joined by ``joiner``; ``attachmentsByRange`` maps each
    ``{offset, 1}`` range to its variable. This is how Shortcuts stores text
    with embedded variables (e.g. ``notes`` + newline + ``url``).
    """
    string_parts: list[str] = []
    attachments: dict[str, Any] = {}
    offset = 0
    for i, (uuid, output_name) in enumerate(pieces):
        if i:
            string_parts.append(joiner)
            offset += len(joiner)
        string_parts.append("￼")
        attachments[f"{{{offset}, 1}}"] = _output_attachment(uuid, output_name)
        offset += 1
    return {
        "WFSerializationType": "WFTextTokenString",
        "Value": {
            "string": "".join(string_parts),
            "attachmentsByRange": attachments,
        },
    }


def _get_value_action(key: str, uuid: str, dict_uuid: str) -> dict[str, Any]:
    return _action(
        "is.workflow.actions.getvalueforkey",
        {
            "UUID": uuid,
            "WFDictionaryKey": key,
            "WFInput": _var_token(dict_uuid, "Dictionary"),
        },
    )


def build_reminder_shortcut(*, name: str = "Add Reminder") -> bytes:
    """Build an **unsigned** Apple ``.shortcut`` file as binary-plist bytes.

    The generated workflow implements the same contract as
    :func:`shortcuts_reminder_url`: it takes text input (the JSON payload),
    parses it into a dictionary, reads the fixed keys ``title`` / ``due`` /
    ``notes`` / ``url``, and adds a Reminder whose notes are ``notes`` + a
    newline + ``url`` and whose due alarm comes from ``due``.

    Action pipeline (documented, stable identifiers):

        1. ``is.workflow.actions.detect.dictionary``  — Get Dictionary from Input
        2. ``is.workflow.actions.getvalueforkey`` × 4 — title / due / notes / url
        3. ``is.workflow.actions.addnewreminder``     — Add New Reminder

    The workflow is stored under the ``WFWorkflowActions`` key and serialized
    with :mod:`plistlib` in ``FMT_BINARY`` (the format Shortcuts expects).

    **Honest Apple limits — do not over-promise.** This file is *not* signed:
    an Apple-signed iCloud share link can only be minted by Apple, never from
    code. Installing an unsigned ``.shortcut`` therefore requires the user to
    enable **"Allow Untrusted Shortcuts"** in Settings and to run the Shortcut
    **once manually** to grant Reminders access. The recommended production
    path is instead a signed iCloud link published once by a human (source
    "icloud" in :func:`reminder_setup_instructions`).

    .. note::
       The action wiring follows Apple's documented identifiers and the
       standard magic-variable serialization, but has **not** been round-trip
       verified on a physical Apple device (no such device in CI). Treat a
       first import on-device as a one-time validation step and adjust the
       alarm/notes parameters there if Apple's runtime expects a variant.

    Args:
        name: Human-visible Shortcut name embedded in the workflow. Must match
            the ``name`` you later pass to :func:`shortcuts_reminder_url`.

    Returns:
        The ``.shortcut`` file contents as binary-plist ``bytes``.
    """
    dict_uuid = str(_uuid4())
    title_uuid = str(_uuid4())
    due_uuid = str(_uuid4())
    notes_uuid = str(_uuid4())
    url_uuid = str(_uuid4())

    actions = [
        # 1. Parse the text input into a dictionary.
        _action("is.workflow.actions.detect.dictionary", {"UUID": dict_uuid}),
        # 2. Pull the fixed keys out of the dictionary.
        _get_value_action("title", title_uuid, dict_uuid),
        _get_value_action("due", due_uuid, dict_uuid),
        _get_value_action("notes", notes_uuid, dict_uuid),
        _get_value_action("url", url_uuid, dict_uuid),
        # 3. Create the Reminder: title, notes = notes + "\n" + url, due alarm.
        _action(
            "is.workflow.actions.addnewreminder",
            {
                "WFReminderTitle": _text_token([(title_uuid, "Dictionary Value")]),
                "WFReminderNotes": _text_token(
                    [
                        (notes_uuid, "Dictionary Value"),
                        (url_uuid, "Dictionary Value"),
                    ],
                    joiner="\n",
                ),
                "WFAlarms": {
                    "Value": {
                        "WFAlarmType": "AlarmFixed",
                        "WFDate": _var_token(due_uuid, "Dictionary Value"),
                    },
                    "WFSerializationType": "WFArrayParameterState",
                },
            },
        ),
    ]

    workflow: dict[str, Any] = {
        "WFWorkflowName": name,
        "WFWorkflowClientVersion": "2607.0.5",
        "WFWorkflowMinimumClientVersion": 900,
        "WFWorkflowMinimumClientVersionString": "900",
        "WFWorkflowIcon": {
            "WFWorkflowIconStartColor": 4292093695,
            "WFWorkflowIconGlyphNumber": 61440,
        },
        "WFWorkflowImportQuestions": [],
        "WFWorkflowTypes": ["NCWidget", "WatchKit"],
        "WFWorkflowInputContentItemClasses": [
            "WFStringContentItem",
            "WFDictionaryContentItem",
        ],
        "WFWorkflowActions": actions,
    }
    return _plistlib.dumps(workflow, fmt=_plistlib.FMT_BINARY)


def write_reminder_shortcut(path: str, *, name: str = "Add Reminder") -> None:
    """Write :func:`build_reminder_shortcut` output to ``path``.

    Args:
        path: Destination file path (``.shortcut`` extension recommended).
        name: Shortcut name (see :func:`build_reminder_shortcut`).
    """
    data = build_reminder_shortcut(name=name)
    with open(_os.fspath(path), "wb") as fh:
        fh.write(data)


