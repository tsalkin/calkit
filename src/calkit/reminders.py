def reminder_setup_html(
    *,
    install_url: str,
    source: str = "icloud",
    lang: str = "ru",
    labels: Optional[Mapping[str, str]] = None,
    mode: Optional[str] = None,
) -> str:
    """Render a self-contained first-run **setup** page for the Shortcut.

    The page shows the numbered steps from
    :func:`reminder_setup_instructions` (chosen by ``source``), an **"Install
    the Shortcut"** button pointing at ``install_url`` (either a signed iCloud
    link, or a URL your app serves that streams the bytes from
    :func:`build_reminder_shortcut`), and a secondary **"continue"** button
    for after the user has installed it.

    This helper renders *only* the setup UI. Whether the Shortcut is already
    installed is **state the project owns** — decide that yourself and render
    this setup page vs. the per-task :func:`reminder_landing_html`
    accordingly. The "continue" button is a hook (``id="reminder-continue"``,
    ``href="#"``) the project wires to its own next step.

    Apple detection mirrors :func:`reminder_landing_html`: when
    ``mode="unknown"`` the page shows the **same warning** that a non-Apple
    visitor may be in the wrong place, and an inline ``<script>`` re-checks the
    client's platform (including iPadOS masquerade via ``maxTouchPoints``) and
    hides the warning if Apple is found. Any ``mode`` other than ``"unknown"``
    (including the ``None`` default) renders without the warning.

    Args:
        install_url: URL the install button opens (iCloud link or your own
            ``.shortcut`` download endpoint).
        source: ``"icloud"`` (default) or ``"untrusted"`` — selects which step
            list to render.
        lang: ``"ru"`` (default) or ``"en"``.
        labels: Optional overrides for any of ``title``, ``intro``,
            ``install``, ``continue``, ``warning``.
        mode: ``"unknown"`` to surface the not-Apple warning; anything else
            (or ``None``) renders it hidden.

    Returns:
        A complete, dependency-free HTML document. All interpolated values are
        escaped.
    """
    base = _DEFAULT_SETUP_LABELS.get(lang, _DEFAULT_SETUP_LABELS["en"])
    text = dict(base)
    if labels:
        text.update(labels)

    steps = reminder_setup_instructions(lang=lang, source=source)
    steps_html = "\n".join(f"      <li>{_escape(s)}</li>" for s in steps)

    show_warning = mode == "unknown"
    warning_style = "" if show_warning else "display:none;"

    href = _escape(install_url, quote=True)
    lbl_title = _escape(text["title"])
    lbl_intro = _escape(text["intro"])
    lbl_install = _escape(text["install"])
    lbl_continue = _escape(text["continue"])
    lbl_warning = _escape(text["warning"])
    lang_attr = _escape(lang, quote=True)

    return f"""<!DOCTYPE html>
<html lang="{lang_attr}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{lbl_title}</title>
<style>
  body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
         margin: 0; padding: 2rem 1rem; background: #f5f5f7; color: #1d1d1f;
         display: flex; justify-content: center; }}
  .card {{ background: #fff; border-radius: 16px; padding: 2rem 1.5rem;
          max-width: 30rem; width: 100%; box-shadow: 0 2px 12px rgba(0,0,0,.08); }}
  h1 {{ font-size: 1.25rem; margin: 0 0 .5rem; text-align: center; }}
  .intro {{ margin: 0 0 1.25rem; color: #555; text-align: center; }}
  .warning {{ background: #fff8e1; border: 1px solid #ffe082; color: #6d4c00;
             border-radius: 12px; padding: .9rem 1rem; margin: 0 0 1.25rem;
             font-size: .95rem; line-height: 1.4; }}
  ol {{ margin: 0 0 1.5rem; padding-left: 1.25rem; line-height: 1.5; }}
  li {{ margin: 0 0 .6rem; }}
  .btn {{ display: block; text-align: center; text-decoration: none;
         font-size: 1.05rem; font-weight: 600; padding: .85rem 1.5rem;
         border-radius: 12px; box-sizing: border-box; margin: 0 0 .75rem; }}
  .btn-install {{ background: #007aff; color: #fff; }}
  .btn-install:active {{ background: #0062cc; }}
  .btn-continue {{ background: #e8e8ed; color: #1d1d1f; }}
  .btn-continue:active {{ background: #d8d8dd; }}
</style>
</head>
<body>
  <div class="card">
    <h1>{lbl_title}</h1>
    <p class="intro">{lbl_intro}</p>
    <div class="warning" id="reminder-warning" style="{warning_style}">{lbl_warning}</div>
    <ol id="reminder-steps">
{steps_html}
    </ol>
    <a class="btn btn-install" id="reminder-install" href="{href}">{lbl_install}</a>
    <a class="btn btn-continue" id="reminder-continue" href="#">{lbl_continue}</a>
  </div>
  <script>
    (function () {{
      var ua = navigator.userAgent || "";
      var plat = navigator.platform || "";
      var s = (ua + " " + plat).toLowerCase();
      var isApple = /iphone|ipad|ipod|macintosh|mac os x|macintel|macppc/.test(s) ||
                    (navigator.maxTouchPoints > 1 && /macintosh|macintel/.test(s));
      if (isApple) {{
        var warn = document.getElementById("reminder-warning");
        if (warn) {{ warn.style.display = "none"; }}
      }}
    }})();
  </script>
</body>
</html>"""
