"""Apple Reminders via Apple Shortcuts — pure string helpers.

Framework-agnostic and offline: task data in, strings out. No network, no
auth, no secrets. The functions here help a project drive Apple's Shortcuts
app to create a **Reminders** task, and detect whether the current visitor is
on an Apple platform (so the button can be surfaced appropriately).

Mechanics (out of scope for this library, but useful to understand the API):

1. **One-time setup (first run).** The user installs one Shortcut that reads
   its dictionary *input* and adds a Reminder. Two install sources exist:

   * **(A) built-in unsigned ``.shortcut``** — generated by this library via
     :func:`build_reminder_shortcut` / :func:`write_reminder_shortcut`. Fully
     self-contained (no external hosting), but on the device it requires
     "Allow Untrusted Shortcuts" plus one manual run to grant Reminders
     access. **Honest limit:** an Apple-*signed* iCloud link cannot be minted
     from code — signing happens on Apple's side.
   * **(B) signed iCloud share link** — published once by a human
     (``https://www.icloud.com/shortcuts/...``); frictionless for users and
     the recommended production path. The library does not (cannot) generate
     it; you pass it in as configuration.

   :func:`reminder_setup_instructions` / :func:`reminder_setup_html` render the
   first-run onboarding for *either* source.
2. **Per-task launch.** For each task the project builds a
   ``shortcuts://run-shortcut?name=...&input=<JSON>`` URL with
   :func:`shortcuts_reminder_url` and opens it on the Apple device; the
   Shortcut receives the JSON as input and creates the Reminder.

The JSON payload uses a **fixed set of keys** so the Shortcut can be built
against a stable contract:

    title  (str)        -- reminder title
    due    (str|None)   -- ISO-8601 due date/time (with offset if tz-aware)
    notes  (str|None)   -- free-text notes
    url    (str|None)   -- associated link

Extra keys may be merged in via ``shortcut_input_extra``.

Public API:
    shortcuts_reminder_url(...)     -> str    # shortcuts:// launch URL
    detect_apple(user_agent)        -> AppleDevice
    reminder_entry_mode(ua)         -> str    # "apple" | "unknown"
    reminder_landing_html(...)      -> str    # per-task landing page
    build_reminder_shortcut(...)    -> bytes  # unsigned .shortcut plist
    write_reminder_shortcut(...)    -> None   # write that plist to a file
    reminder_setup_instructions(...) -> list  # ordered first-run steps
    reminder_setup_html(...)        -> str    # first-run setup page
"""

